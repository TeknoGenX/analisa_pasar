class Command(BaseCommand):
    help = 'Menambahkan daftar lengkap instrumen pasar termasuk Top Buy/Sell IDX'

    def handle(self, *args, **options):
        self.stdout.write(self.style.NOTICE("Memulai proses seeding seluruh instrumen pasar..."))
        created_count = 0
        updated_count = 0

        for item in ALL_INSTRUMENTS:
            inst, created = MarketInstrument.objects.update_or_create(
                symbol=item['symbol'],
                defaults={
                    'name': item['name'],
                    'market_category': item['market_category'],
                    'is_active': True
                }
            )
            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(self.style.SUCCESS(
            f"Selesai! {created_count} instrumen baru ditambahkan, "
            f"{updated_count} diperbarui. Total instrumen aktif: {MarketInstrument.objects.filter(is_active=True).count()}"
        ))